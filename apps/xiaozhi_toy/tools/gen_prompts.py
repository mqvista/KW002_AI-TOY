"""
Embed the Ogg/Opus prompt sounds in assets/sounds into src/xz_prompts_data.c.

    python tools/gen_prompts.py

Most sounds come from 78/xiaozhi-esp32 (MIT, see assets/sounds/LICENSE.xiaozhi-esp32);
charging, charger_removed, connect_ap, net_* and ssid_* are synthesized by tools/tts_prompts.py.
Re-run after adding or replacing a sound; the generated file is committed.
"""

import os
import re

APP_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOUND_DIR = os.path.join(APP_DIR, 'assets', 'sounds')
OUT_C = os.path.join(APP_DIR, 'src', 'xz_prompts_data.c')


def c_name(file_name):
    stem = os.path.splitext(file_name)[0]
    return 'XZ_SND_' + re.sub(r'[^0-9A-Za-z]', '_', stem).upper()


def main():
    files = sorted(f for f in os.listdir(SOUND_DIR) if f.endswith('.ogg'))
    out = [
        '/**',
        ' * @file xz_prompts_data.c',
        ' * @brief Embedded Ogg/Opus prompt sounds. Generated by tools/gen_prompts.py, do not edit.',
        ' *',
        ' * Sounds from 78/xiaozhi-esp32, MIT License, see assets/sounds/LICENSE.xiaozhi-esp32;',
        ' * charging, charger_removed, connect_ap, net_*, ssid_*: tools/tts_prompts.py (Windows Huihui voice).',
        ' */',
        '',
        '#include "xz_prompts.h"',
        '',
    ]
    for f in files:
        data = open(os.path.join(SOUND_DIR, f), 'rb').read()
        name = c_name(f)
        out.append(f'/* {f}, {len(data)} bytes */')
        out.append(f'static const uint8_t {name.lower()}[{len(data)}] = {{')
        for i in range(0, len(data), 16):
            out.append('    ' + ', '.join(f'0x{b:02x}' for b in data[i:i + 16]) + ',')
        out.append('};')
        out.append('')
    out.append('const XZ_SOUND_T g_xz_sounds[XZ_SND_MAX] = {')
    for f in files:
        name = c_name(f)
        out.append(f'    [{name}] = {{{name.lower()}, sizeof({name.lower()})}},')
    out.append('};')
    out.append('')
    open(OUT_C, 'w', newline='\n').write('\n'.join(out))

    print('enum entries for xz_prompts.h:')
    for f in files:
        print(f'    {c_name(f)},')
    print(f'wrote {OUT_C} ({len(files)} sounds)')


if __name__ == '__main__':
    main()
